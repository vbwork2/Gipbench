#!/usr/bin/env python3
"""Phase 2 runtime training-correctness checks (RESEARCH_RECOVERY.md section 3; rules registered there before the run).

Uses the real training code: Icefall `zipformer/finetune_cs.py` as generated by `gipbench.model.train.patch_finetune`
(imported as a module), its `get_params` / `get_model` / `load_model_params` / `compute_loss` / data module, the exact
freeze snippet that the patch injects, and the ScaledAdam + Eden construction of `finetune.py`. CPU, fp32 (the WSL GPU
is unavailable, so fp16 / GradScaler is NOT exercised here).

  PYTHONPATH=src:$HOME/jiwer_target ~/.venvs/gipbench-ft/bin/python scripts/recovery_p2_train_checks.py \
      --icefall ~/icefall --work data/work/recovery/p2

Data: the first N rows (sha256 order) of pool/vivos_train@v3 (the X0 training pool). No bench or dev audio.
"""
import argparse
import hashlib
import json
import logging
import os
import subprocess
import sys
import textwrap
import time
from pathlib import Path

import numpy as np

REPO = Path(__file__).resolve().parents[1]
GIP = REPO / "models/gip15"
POOL = REPO / "data/releases/pool/vivos_train@v3/manifest.jsonl"
FREEZE = "encoder_embed.,encoder.encoders.0.,encoder.encoders.1."   # X0
GROUPS = ("encoder_embed.", *(f"encoder.encoders.{i}." for i in range(6)), "encoder.downsample_output.",
          "decoder.", "joiner.", "simple_am_proj.", "simple_lm_proj.")


def group_of(name):
    return next((g for g in GROUPS if name.startswith(g)), "other")


def setup_icefall(icefall):
    asr = icefall / "egs/librispeech/ASR"
    for d in (icefall, asr, asr / "zipformer"):
        if str(d) not in sys.path:
            sys.path.insert(0, str(d))
    return asr


def sample_rows(n):
    rows = [json.loads(ln) for ln in POOL.read_text(encoding="utf-8").splitlines() if ln.strip()]
    rows.sort(key=lambda r: hashlib.sha256(r["id"].encode()).hexdigest())
    return rows


def build_cuts(rows, path):
    """Same text and recording construction as gipbench.model.features.to_lhotse (no augmentation)."""
    from lhotse import CutSet, Recording, RecordingSet, SupervisionSegment, SupervisionSet
    from gipbench.core.textnorm import Catalog, model_case_text

    cat = Catalog.load(str(REPO / "data/catalogs/train_v1/catalog.tsv"))
    recs, sups = [], []
    for r in rows:
        rid = f"p2-{r['id']}"
        rec = Recording.from_file(str((POOL.parent / r["audio"]).resolve()), recording_id=rid)
        recs.append(rec)
        sups.append(SupervisionSegment(id=rid, recording_id=rid, start=0.0, duration=rec.duration, channel=0,
                                       text=model_case_text(r.get("text_tagged") or r.get("text") or "", "upper", cat), language="vi"))
    cuts = CutSet.from_manifests(recordings=RecordingSet.from_recordings(recs),
                                 supervisions=SupervisionSet.from_segments(sups))
    if any(r.sampling_rate != 16000 for r in recs):
        cuts = cuts.resample(16000)
    cuts.to_file(path)
    return cuts


def tokenizer_audit(sp):
    """T0: every training text of the X0 pool through model_case_text + the BPE: <unk> pieces and odd characters."""
    from gipbench.core.textnorm import Catalog, model_case_text

    cat = Catalog.load(str(REPO / "data/catalogs/train_v1/catalog.tsv"))
    rows = [json.loads(ln) for ln in POOL.read_text(encoding="utf-8").splitlines() if ln.strip()]
    unk, chars, n_tok, examples = 0, {}, 0, []
    vocab_chars = {c for i in range(sp.get_piece_size()) for c in sp.id_to_piece(i)}
    for r in rows:
        t = model_case_text(r.get("text_tagged") or r.get("text") or "", "upper", cat)
        ids = sp.encode(t)
        n_tok += len(ids)
        k = sum(i == sp.unk_id() for i in ids)
        unk += k
        if k and len(examples) < 10:
            examples.append(t)
        for c in t:
            if c != " " and c not in vocab_chars:
                chars[c] = chars.get(c, 0) + 1
    return {"rows": len(rows), "tokens": n_tok, "unk_tokens": unk, "chars_outside_vocab": chars,
            "unk_examples": examples, "lowercase_rows": sum(
                model_case_text(r.get("text_tagged") or r.get("text") or "", "upper", cat) != model_case_text(r.get("text_tagged") or r.get("text") or "", "upper", cat).upper()
                for r in rows)}


def make_args(F, work, lr, max_duration, extra=()):
    parser = F.get_parser()
    F.LibriSpeechAsrDataModule.add_arguments(parser)
    argv = ["--world-size", "1", "--use-fp16", "0", "--use-transducer", "1", "--use-ctc", "0",
            "--exp-dir", str(work / "exp"), "--bpe-model", str(GIP / "bpe.model"), "--freeze-modules", FREEZE,
            "--train-cuts", str(work / "train_cuts.jsonl.gz"), "--valid-cuts", str(work / "valid_cuts.jsonl.gz"),
            "--on-the-fly-feats", "True", "--num-workers", "0", "--num-buckets", "2", "--bucketing-sampler", "False", "--shuffle", "False",
            "--base-lr", str(lr), "--max-duration", str(max_duration), "--enable-musan", "False",
            "--enable-spec-aug", "False", "--do-finetune", "1", "--finetune-ckpt", str(GIP / "init_ft.pt"),
            "--start-epoch", "1", "--num-epochs", "1", "--seed", "0", "--manifest-dir", str(work), *extra]
    return parser.parse_args(argv)


def build(F, PF, args):
    import sentencepiece as spm
    from icefall.utils import get_parameter_groups_with_lrs
    from optim import Eden, ScaledAdam

    params = F.get_params()
    params.update(vars(args))
    sp = spm.SentencePieceProcessor()
    sp.load(params.bpe_model)
    params.blank_id = sp.piece_to_id("<blk>")
    params.vocab_size = sp.get_piece_size()
    model = F.get_model(params)
    F.load_model_params(ckpt=params.finetune_ckpt, model=model, init_modules=None)
    ns = {"params": params, "model": model, "logging": logging}
    exec(textwrap.dedent(PF.FREEZE), ns)  # the exact code the patch injects into finetune_cs.py
    optimizer = ScaledAdam(get_parameter_groups_with_lrs(model, lr=params.base_lr, include_names=True),
                           lr=params.base_lr, clipping_scale=2.0)
    scheduler = Eden(optimizer, params.lr_batches, params.lr_epochs)
    return params, sp, model, optimizer, scheduler


def losses_of(F, params, model, sp, batch):
    """The model call inside compute_loss, returning the two transducer losses separately."""
    import k2
    import torch

    feature = batch["inputs"]
    lens = batch["supervisions"]["num_frames"]
    y = k2.RaggedTensor(sp.encode(batch["supervisions"]["text"], out_type=int))
    simple, pruned, _ = model(x=feature, x_lens=lens, y=y, prune_range=params.prune_range,
                              am_scale=params.am_scale, lm_scale=params.lm_scale)[:3]
    frames = int((lens // params.subsampling_factor).sum())
    return simple, pruned, frames


def grad_norms(model):
    out = {}
    for n, p in model.named_parameters():
        if p.grad is not None:
            g = group_of(n)
            out[g] = out.get(g, 0.0) + float(p.grad.double().pow(2).sum())
    return {k: v ** 0.5 for k, v in out.items()}


def flat_grad(model, prefix):
    import torch

    return torch.cat([p.grad.flatten().double() for n, p in model.named_parameters()
                      if n.startswith(prefix) and p.grad is not None])


def train_step(F, params, model, optimizer, scheduler, sp, batch):
    """One iteration of finetune.py train_one_epoch with fp16 disabled (scaler.step == optimizer.step)."""
    model.train()
    if params.batch_idx_train % 10 == 0:
        F.set_batch_count(model, F.get_adjusted_batch_count(params))
    params.batch_idx_train += 1
    loss, info = F.compute_loss(params=params, model=model, sp=sp, batch=batch, is_training=True)
    loss.backward()
    gn = grad_norms(model)
    scheduler.step_batch(params.batch_idx_train)
    optimizer.step()
    optimizer.zero_grad()
    return {"loss_per_frame": info["loss"] / info["frames"], "simple": info["simple_loss"] / info["frames"],
            "pruned": info["pruned_loss"] / info["frames"], "lr": scheduler.get_last_lr()[0], "grad_norm": gn}


def eval_losses(F, params, model, sp, batch):
    import torch

    model.eval()
    with torch.no_grad():
        s, p, f = losses_of(F, params, model, sp, batch)
    model.train()
    return {"simple": float(s) / f, "pruned": float(p) / f}


def snapshot(model):
    return {n: p.detach().clone() for n, p in model.named_parameters()}


def update_report(model, init, frozen_prefixes):
    import torch

    rep, frozen_changed, train_unchanged = {}, [], []
    for n, p in model.named_parameters():
        d = (p.detach() - init[n]).double()
        g = group_of(n)
        e = rep.setdefault(g, {"delta_sq": 0.0, "ref_sq": 0.0, "tensors": 0, "changed": 0})
        e["delta_sq"] += float(d.pow(2).sum())
        e["ref_sq"] += float(init[n].double().pow(2).sum())
        e["tensors"] += 1
        changed = not torch.equal(p.detach(), init[n])
        e["changed"] += changed
        if any(n.startswith(x) for x in frozen_prefixes):
            if changed:
                frozen_changed.append((n, float(d.abs().max())))
        elif not changed:
            train_unchanged.append(n)
    for e in rep.values():
        e["rel_update"] = (e.pop("delta_sq") / max(e.pop("ref_sq"), 1e-30)) ** 0.5
    return rep, frozen_changed, train_unchanged


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--icefall", type=Path, required=True)
    ap.add_argument("--work", type=Path, required=True)
    ap.add_argument("--n-train", type=int, default=6)
    ap.add_argument("--steps", type=int, default=12)
    ap.add_argument("--lr", type=float, default=3e-4)
    ap.add_argument("--threads", type=int, default=8)
    args = ap.parse_args()
    import torch

    torch.set_num_threads(args.threads)
    torch.manual_seed(0)
    asr = setup_icefall(args.icefall.expanduser())
    sys.path.insert(0, str(REPO / "src"))
    from gipbench.model.train import patch_finetune as PF

    subprocess.run([sys.executable, "-m", "gipbench.model.train.patch_finetune", "--icefall",
                    str(args.icefall.expanduser())], check=True, env=dict(os.environ, PYTHONPATH=str(REPO / "src")))
    import finetune_cs as F

    work = args.work.resolve()
    (work / "exp").mkdir(parents=True, exist_ok=True)
    res = {"started": time.strftime("%Y-%m-%dT%H:%M:%S%z"), "torch": torch.__version__, "device": "cpu", "fp16": False,
           "script_sha256": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
           "finetune_cs_sha256": hashlib.sha256((asr / "zipformer/finetune_cs.py").read_bytes()).hexdigest()}
    rows = sample_rows(args.n_train)
    train_rows, valid_rows = rows[:args.n_train], rows[args.n_train:args.n_train + 4]
    build_cuts(train_rows, work / "train_cuts.jsonl.gz")
    build_cuts(valid_rows, work / "valid_cuts.jsonl.gz")
    res["train_ids"] = [r["id"] for r in train_rows]
    res["pool_sha256"] = hashlib.sha256(POOL.read_bytes()).hexdigest()

    fargs = make_args(F, work, args.lr, max_duration=200)
    params, sp, model, optimizer, scheduler = build(F, PF, fargs)
    res["T0_tokenizer"] = tokenizer_audit(sp)
    init = snapshot(model)
    frozen = [x for x in FREEZE.split(",") if x]
    res["n_params"] = sum(p.numel() for p in model.parameters())
    res["n_frozen"] = sum(p.numel() for n, p in model.named_parameters() if not p.requires_grad)
    res["frozen_rms_over_3"] = [n for n, p in model.named_parameters()
                                if not p.requires_grad and float(p.detach().pow(2).mean().sqrt()) > 3.0]

    from lhotse import load_manifest_lazy
    dm = F.LibriSpeechAsrDataModule(fargs)
    batch = next(iter(dm.train_dataloaders(load_manifest_lazy(work / "train_cuts.jsonl.gz"))))
    res["batch"] = {"utts": len(batch["supervisions"]["text"]), "feat_shape": list(batch["inputs"].shape),
                    "texts": batch["supervisions"]["text"]}

    # T1 forward + loss values (pretrained model, eval and train mode), scales at batch 0 vs after warm-up
    F.set_batch_count(model, F.get_adjusted_batch_count(params))
    res["T1_forward"] = {"eval": eval_losses(F, params, model, sp, batch), "warm_step": params.warm_step,
                         "simple_loss_scale_cfg": params.simple_loss_scale,
                         "scales_at_batch_1": {"simple": 1.0 - (1 / params.warm_step) * (1.0 - params.simple_loss_scale),
                                               "pruned": 0.1 + 0.9 * (1 / params.warm_step)},
                         "scales_after_warmup": {"simple": params.simple_loss_scale, "pruned": 1.0}}

    # T2 gradient flow, per loss term (same dropout draw for both: seeded forward)
    model.train()
    grads = {}
    for term in ("simple", "pruned"):
        optimizer.zero_grad()
        torch.manual_seed(1)
        s, p, f = losses_of(F, params, model, sp, batch)
        (s if term == "simple" else p).backward()
        grads[term] = {"norms": grad_norms(model), "enc": flat_grad(model, "encoder."),
                       "frozen_grads_not_none": [n for n, q in model.named_parameters()
                                                 if not q.requires_grad and q.grad is not None]}
    gs, gp = grads["simple"]["enc"], grads["pruned"]["enc"]
    cos = float(gs @ gp / (gs.norm() * gp.norm()))

    def mix(ws, wp):
        return float((ws * gs + wp * gp).norm()), float((wp * gp).norm() / (ws * gs + wp * gp).norm())
    sc1, sce = res["T1_forward"]["scales_at_batch_1"], res["T1_forward"]["scales_after_warmup"]
    res["T2_gradients"] = {
        "per_group_norm_simple": grads["simple"]["norms"], "per_group_norm_pruned": grads["pruned"]["norms"],
        "encoder_cosine_simple_vs_pruned": cos,
        "encoder_grad_norm_at_batch1": mix(sc1["simple"], sc1["pruned"])[0],
        "pruned_share_of_encoder_grad_at_batch1": mix(sc1["simple"], sc1["pruned"])[1],
        "pruned_share_of_encoder_grad_after_warmup": mix(sce["simple"], sce["pruned"])[1],
        "frozen_params_with_grad": grads["simple"]["frozen_grads_not_none"] + grads["pruned"]["frozen_grads_not_none"],
        "trainable_groups_without_grad": sorted({group_of(n) for n, q in model.named_parameters()
                                                 if q.requires_grad} - set(grads["pruned"]["norms"]))}
    optimizer.zero_grad()

    # T3 optimizer + scheduler + parameter updates (repeat the same batch: determinism, no augmentation)
    traj = [train_step(F, params, model, optimizer, scheduler, sp, batch) for _ in range(args.steps)]
    rep, frozen_changed, train_unchanged = update_report(model, init, frozen)
    res["T3_optimizer"] = {"steps": traj, "eval_after": eval_losses(F, params, model, sp, batch),
                           "update_by_group": rep, "frozen_changed": frozen_changed,
                           "trainable_unchanged": train_unchanged}

    # T4 checkpoint save (finetune.py's call) + reload into a fresh model
    from icefall.checkpoint import save_checkpoint_with_global_batch_idx
    save_checkpoint_with_global_batch_idx(out_dir=params.exp_dir, global_batch_idx=params.batch_idx_train, model=model,
                                          model_avg=None, params=params, optimizer=optimizer, scheduler=scheduler,
                                          sampler=None, scaler=None, rank=0)
    ck = Path(params.exp_dir) / f"checkpoint-{params.batch_idx_train}.pt"
    fresh = F.get_model(params)
    state = torch.load(ck, map_location="cpu", weights_only=False)
    load = fresh.load_state_dict(state["model"], strict=False)
    model.eval(), fresh.eval()
    x = batch["inputs"]
    lens = batch["supervisions"]["num_frames"]
    with torch.no_grad():
        a, _ = model.forward_encoder(x, lens)
        b, _ = fresh.forward_encoder(x, lens)
    res["T4_checkpoint"] = {"path": str(ck), "missing": list(load.missing_keys), "unexpected": list(load.unexpected_keys),
                            "tensors_not_equal": [n for n, p in fresh.state_dict().items()
                                                  if not torch.equal(p, model.state_dict()[n])],
                            "encoder_out_max_abs_diff": float((a - b).abs().max()),
                            "keys_saved": sorted(state)}

    # T5 export the saved checkpoint through the X0 path (--iter, average_checkpoints) and compare with torch
    cmd = [sys.executable, "./zipformer/export-onnx.py", "--tokens", str(GIP / "tokens.txt"), "--exp-dir",
           str(params.exp_dir), "--use-transducer", "1", "--use-ctc", "0", "--iter", str(params.batch_idx_train),
           "--avg", "1", "--use-averaged-model", "0", "--enable-int8-quantization", "1"]
    log = work / "export.log"
    with open(log, "w") as fh:
        rc = subprocess.run(cmd, cwd=asr, stdout=fh, stderr=subprocess.STDOUT,
                            env=dict(os.environ, PYTHONPATH=str(args.icefall.expanduser()))).returncode
    t5 = {"returncode": rc, "cmd": cmd}
    if rc == 0:
        import onnxruntime as ort
        from beam_search import greedy_search_batch
        from gipformer_mech.onnx_greedy import OnnxTransducer

        md = work / "onnx"
        md.mkdir(exist_ok=True)
        tag = f"iter-{params.batch_idx_train}-avg-1"
        for part in ("encoder", "decoder", "joiner"):
            for suf in (".onnx", ".int8.onnx"):
                src = Path(params.exp_dir) / f"{part}-{tag}{suf}"
                (md / f"{part}{suf}").unlink(missing_ok=True)
                src.rename(md / f"{part}{suf}")
        (md / "tokens.txt").write_bytes((GIP / "tokens.txt").read_bytes())
        arm = OnnxTransducer(md, "fp32", 4)
        errs, same = [], 0
        for i in range(x.shape[0]):
            n = int(lens[i])
            with torch.no_grad():
                e, el = fresh.forward_encoder(x[i:i + 1, :n], lens[i:i + 1])
                proj = fresh.joiner.encoder_proj(e)[0, :int(el[0])].numpy()
                tids = greedy_search_batch(model=fresh, encoder_out=e, encoder_out_lens=el)[0]
            o = arm.encode(x[i, :n].numpy())
            errs.append(float(np.linalg.norm(o - proj) / np.linalg.norm(proj)))
            same += arm.greedy(o)["ids"] == tids
        t5.update(encoder_relerr_max=max(errs), greedy_same=same, utts=int(x.shape[0]))
    res["T5_export"] = t5
    res["finished"] = time.strftime("%Y-%m-%dT%H:%M:%S%z")
    out = work / "p2_checks.json"
    out.write_text(json.dumps(res, ensure_ascii=False, indent=1, default=str) + "\n", encoding="utf-8")
    brief = {k: v for k, v in res.items() if k.startswith("T")}
    for t in brief.get("T3_optimizer", {}).get("steps", []):
        t.pop("grad_norm", None)
    print(json.dumps(brief, ensure_ascii=False, indent=1, default=str))


if __name__ == "__main__":
    main()
